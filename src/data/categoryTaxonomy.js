export function getCategoryTaxonomyById(id) {
  return categoryTaxonomy.find((category) => category.id === id) ?? null;
}

export function getCategoryTaxonomyForEvent(event) {
  const eventCategory = String(event?.category ?? "").toLowerCase();

  if (!eventCategory) return null;

  return (
    categoryTaxonomy.find((category) =>
      category.legacyCategoryIds.includes(eventCategory)
    ) ?? null
  );
}
